"""The shell's embedded fonts and icon, as the object the harnesses link.

src/shell/shell_embed.c holds about 15 MB of generated byte arrays that
shell.meta.h declares extern. build.sh compiles it to build/shell_embed.o
only when that is missing or older than its sources; this does the same,
so a harness run after a build reuses the build's object.
"""
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]
SOURCES = [ROOT/'src/shell/shell_embed.c', ROOT/'src/shell/generated/shell.embed.meta.c']


def shell_embed_object(compiler):
    """Return build/shell_embed.o, compiling it with `compiler` (an argv list) if stale."""
    obj = ROOT/'build/shell_embed.o'
    if not obj.exists() or any(s.stat().st_mtime > obj.stat().st_mtime for s in SOURCES):
        tmp = obj.with_suffix('.o.tmp')
        subprocess.run(compiler + ['-g', '-O0', '-D_GNU_SOURCE', '-I'+str(ROOT/'src'),
                                   '-c', str(SOURCES[0]), '-o', str(tmp)], check=True)
        tmp.replace(obj)
    return obj
